"""Database layer for the Community Resource Navigator.

Two interchangeable backends behind one interface:

  - Postgres (Supabase) when the DATABASE_URL env var is set - production.
  - SQLite (resources.db) otherwise - local development, zero setup.

Callers write portable SQL with `?` placeholders and treat rows like
sqlite3.Row (row[0], row["col"], dict(row), tuple unpacking). The wrapper
translates placeholders and row types for Postgres. Two backend-specific
spots are wrapped in helpers: insert_returning_id() and init_db().

Keep queries portable: no sqlite date functions (compute dates in Python),
no bare `%` literals in SQL (pass LIKE patterns as parameters), no
COLLATE NOCASE (use lower(...)).
"""
import os
import sqlite3
from pathlib import Path

DB_PATH = Path(__file__).parent / "resources.db"
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
IS_PG = DATABASE_URL.startswith(("postgres://", "postgresql://"))

if IS_PG:
    import psycopg


# ---------- schema ----------

_TABLES_COMMON = """
CREATE TABLE IF NOT EXISTS resources (
    id {pk},
    category TEXT NOT NULL,
    type TEXT,
    area TEXT,
    org_name TEXT NOT NULL,
    phone TEXT,
    email TEXT,
    location TEXT,
    hours TEXT,
    website TEXT,
    notes TEXT,
    bilingual_support TEXT,
    accessibility TEXT,
    insurance_cost TEXT,
    eligibility_criteria TEXT,
    income_based INTEGER,
    has_flyer INTEGER,
    has_application_form INTEGER,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'needs_review', 'inactive')),
    seasonal_note TEXT,
    last_verified_date TEXT,
    verification_note TEXT,
    created_at TEXT NOT NULL DEFAULT {now},
    updated_at TEXT NOT NULL DEFAULT {now}
);
CREATE INDEX IF NOT EXISTS idx_resources_category ON resources(category);
CREATE INDEX IF NOT EXISTS idx_resources_status ON resources(status);

CREATE TABLE IF NOT EXISTS verification_checks (
    id {pk},
    resource_id INTEGER NOT NULL REFERENCES resources(id),
    verdict TEXT NOT NULL CHECK (verdict IN
        ('confirmed', 'changed', 'possibly_inactive', 'unreachable',
         'needs_manual_check', 'error')),
    confidence REAL,
    proposed_changes TEXT,
    evidence TEXT,
    source_url TEXT,
    http_status INTEGER,
    error TEXT,
    checked_at TEXT NOT NULL,
    review_status TEXT NOT NULL DEFAULT 'pending' CHECK (review_status IN
        ('pending', 'approved', 'rejected', 'auto_applied', 'superseded')),
    reviewed_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_checks_review_status ON verification_checks(review_status);
CREATE INDEX IF NOT EXISTS idx_checks_resource ON verification_checks(resource_id);

-- Shareable match lists (resource info only - never any family/patient data)
CREATE TABLE IF NOT EXISTS shared_lists (
    token TEXT PRIMARY KEY,
    payload TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT {now}
);

-- Audit trail: one row per changed field, for every edit however it happened
CREATE TABLE IF NOT EXISTS edit_log (
    id {pk},
    resource_id INTEGER NOT NULL,
    field TEXT NOT NULL,
    old_value TEXT,
    new_value TEXT,
    source TEXT NOT NULL,      -- 'manual edit' | 'verification approved' | 'created'
    changed_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_editlog_resource ON edit_log(resource_id);
"""

SCHEMA_SQLITE = _TABLES_COMMON.format(
    pk="INTEGER PRIMARY KEY AUTOINCREMENT",
    now="(datetime('now'))")
SCHEMA_PG = _TABLES_COMMON.format(
    pk="BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    now="(now()::text)")


# ---------- row + connection wrappers (Postgres only) ----------

class Row:
    """Duck-types sqlite3.Row: row[0], row['col'], dict(row), unpacking."""
    __slots__ = ("_cols", "_vals")

    def __init__(self, cols, vals):
        self._cols = cols
        self._vals = list(vals)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._vals[key]
        return self._vals[self._cols.index(key)]

    def get(self, key, default=None):
        try:
            return self[key]
        except (ValueError, IndexError):
            return default

    def keys(self):
        return list(self._cols)

    def __iter__(self):
        return iter(self._vals)

    def __len__(self):
        return len(self._vals)


class _PgCursor:
    def __init__(self, cur):
        self._cur = cur

    def _cols(self):
        return [d.name for d in self._cur.description]

    def fetchone(self):
        r = self._cur.fetchone()
        return None if r is None else Row(self._cols(), r)

    def fetchall(self):
        cols = self._cols() if self._cur.description else []
        return [Row(cols, r) for r in self._cur.fetchall()]

    def __iter__(self):
        cols = self._cols()
        for r in self._cur:
            yield Row(cols, r)

    @property
    def rowcount(self):
        return self._cur.rowcount

    @property
    def lastrowid(self):  # guard: callers must use insert_returning_id instead
        raise NotImplementedError("use db.insert_returning_id() - portable")


class PgConn:
    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql, params=()):
        cur = self._raw.cursor()
        cur.execute(sql.replace("?", "%s"), list(params))
        return _PgCursor(cur)

    def executescript(self, script):
        self._raw.execute(script)

    def commit(self):
        self._raw.commit()

    def close(self):
        self._raw.close()


# ---------- public interface ----------

def get_conn():
    if IS_PG:
        raw = psycopg.connect(DATABASE_URL)
        raw.prepare_threshold = None  # safe behind Supabase's pooler
        return PgConn(raw)
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def insert_returning_id(conn, sql, params):
    """INSERT and return the new row id, on either backend."""
    if IS_PG:
        return conn.execute(sql + " RETURNING id", params).fetchone()[0]
    return conn.execute(sql, params).lastrowid


def init_db():
    conn = get_conn()
    conn.executescript(SCHEMA_PG if IS_PG else SCHEMA_SQLITE)
    conn.commit()
    conn.close()


if __name__ == "__main__":
    init_db()
    print(f"Initialized {'Postgres (DATABASE_URL)' if IS_PG else DB_PATH}")
